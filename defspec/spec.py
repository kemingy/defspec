DEFAULT_CONTENT_TYPE = "application/json"
ParameterLocation = Literal["query", "header", "cookie", "path"]
_PATH_TEMPLATE = re.compile(r"\{([^{}]+)\}")


@lru_cache(maxsize=8192)
def _normalized_path(path: str) -> str:
    """Cache path strings while checking mutable routes and operation IDs live."""
    return _PATH_TEMPLATE.sub("{}", path)


def _parse_path(path: str) -> tuple[str, frozenset[str]]:
    """Read URL placeholders and check for unmatched braces."""
    parts = _PATH_TEMPLATE.split(path)
    literals = parts[::2]
    if any("{" in part or "}" in part for part in literals):
        raise ValueError(f"Malformed path template: {path!r}")
    return "{}".join(literals), frozenset(parts[1::2])


class OpenAPIInfo(msgspec.Struct, kw_only=True):
    title: str = "OpenAPI"
    description: str = "OpenAPI generated by defspec"
    version: str = "0.1.0"


class OpenAPIParam(msgspec.Struct, kw_only=True):
    name: str
    located_in: ParameterLocation = msgspec.field(default="query", name="in")
    required: bool = True
    description: str = ""
    schema: Union[dict[str, Any], bool]


class JSONSchema(msgspec.Struct, kw_only=True, omit_defaults=True):
    content: dict[str, dict] = msgspec.field(default_factory=dict)

    @classmethod
    def with_schema_content_type(
        cls, schema: dict[str, Any], content_type: Optional[str] = None
    ) -> Self:
        return cls(content={content_type or DEFAULT_CONTENT_TYPE: {"schema": schema}})


class OpenAPIRequestBody(JSONSchema):
    pass


class OpenAPIResponse(JSONSchema):
    description: str = ""

    def __post_init__(self):
        """Supply the response description required by OpenAPI."""
        if not self.description:
            self.description = "OK"


class OpenAPIRoute(msgspec.Struct, kw_only=True, omit_defaults=True):
    summary: str
    operation_id: str = msgspec.field(name="operationId")
    description: str = ""
    parameters: list[OpenAPIParam] = msgspec.field(default_factory=list)
    request_body: Union[OpenAPIRequestBody, msgspec.UnsetType] = msgspec.field(
        name="requestBody", default=msgspec.UNSET
    )
    responses: dict[str, OpenAPIResponse]
    security: Union[list[dict[str, list[str]]], msgspec.UnsetType] = msgspec.UNSET
    deprecated: bool = False


class SecuritySchemeHTTP(msgspec.Struct, tag_field="type", tag="http"):
    scheme: Literal["basic", "bearer"]


class SecuritySchemeAPIKey(msgspec.Struct, tag_field="type", tag="apiKey"):
    name: str
    located_in: Literal["query", "header", "cookie"] = msgspec.field(
        default="header", name="in"
    )


class SecuritySchemeOpenID(msgspec.Struct, tag_field="type", tag="openIdConnect"):
    open_id_connect_url: str = msgspec.field(name="openIdConnectUrl")


class _OAuthFlowMixin:
    __slots__ = ()
    refresh_url: Union[str, None, msgspec.UnsetType]

    def __post_init__(self):
        if self.refresh_url is None:
            self.refresh_url = msgspec.UNSET


class OAuthFlowAuthorizationCode(_OAuthFlowMixin, msgspec.Struct):
    authorization_url: str = msgspec.field(name="authorizationUrl")
    token_url: str = msgspec.field(name="tokenUrl")
    refresh_url: Union[str, None, msgspec.UnsetType] = msgspec.field(
        name="refreshUrl", default=msgspec.UNSET
    )
    scopes: dict[str, str] = msgspec.field(default_factory=dict)


class ImplicitOAuthFlow(_OAuthFlowMixin, msgspec.Struct):
    authorization_url: str = msgspec.field(name="authorizationUrl")
    refresh_url: Union[str, None, msgspec.UnsetType] = msgspec.field(
        name="refreshUrl", default=msgspec.UNSET
    )
    scopes: dict[str, str] = msgspec.field(default_factory=dict)


class PasswordOAuthFlow(_OAuthFlowMixin, msgspec.Struct):
    token_url: str = msgspec.field(name="tokenUrl")
    refresh_url: Union[str, None, msgspec.UnsetType] = msgspec.field(
        name="refreshUrl", default=msgspec.UNSET
    )
    scopes: dict[str, str] = msgspec.field(default_factory=dict)


class ClientCredentialsOAuthFlow(PasswordOAuthFlow):
    pass


class OAuthFlow(msgspec.Struct, omit_defaults=True):
    """OAuth flow type.

    One or more named flows are supported.

    Previous name in OpenAPI 2.0:

    - `authorizationCode`: `accessCode`
    - `implicit`: `implicit`
    - `password`: `password`
    - `clientCredentials`: `application`
    """

    authorization_code: Optional[OAuthFlowAuthorizationCode] = msgspec.field(
        name="authorizationCode", default=None
    )
    implicit: Optional[ImplicitOAuthFlow] = None
    password: Optional[PasswordOAuthFlow] = None
    client_credentials: Optional[ClientCredentialsOAuthFlow] = msgspec.field(
        name="clientCredentials", default=None
    )

    def __post_init__(self):
        if not any(
            (
                self.authorization_code,
                self.implicit,
                self.password,
                self.client_credentials,
            )
        ):
            raise ValueError("At least one OAuth flow must be provided.")


class SecuritySchemeOAuth2(msgspec.Struct, tag_field="type", tag="oauth2"):
    flows: OAuthFlow


class OpenAPIComponent(msgspec.Struct, kw_only=True, omit_defaults=True):
    schemas: dict[str, dict] = msgspec.field(default_factory=dict)
    security_schemes: dict[
        str,
        Union[
            SecuritySchemeHTTP,
            SecuritySchemeAPIKey,
            SecuritySchemeOAuth2,
            SecuritySchemeOpenID,
        ],
    ] = msgspec.field(name="securitySchemes", default_factory=dict)


HTTP_METHODS = Literal[
    "get", "post", "put", "delete", "head", "options", "trace", "patch"
]

__MSGSPEC_STRUCT_DOC__ = inspect.getdoc(msgspec.Struct)


def get_def_doc(obj: Any) -> str:
    """Get the docstring of a type."""
    doc = inspect.getdoc(obj)
    # Ignore msgspec's inherited Struct docstring.
    return doc if doc is not None and doc != __MSGSPEC_STRUCT_DOC__ else ""


def _constrain_parameter_schema(
    base: Union[dict[str, Any], bool],
    constraint: Union[dict[str, Any], bool],
) -> Union[dict[str, Any], bool]:
    """Intersect schemas without overriding a constraint from either source."""
    if base is False or constraint is False:
        return False
    if base is True:
        return constraint
    if constraint is True or base == constraint:
        return base
    schema: dict[str, Any] = {"allOf": [base, constraint]}
    description = constraint.get("description", base.get("description"))
    if description is not None:
        schema["description"] = description
    return schema


def _check_parameter_constraints(
    schema: dict, properties: dict, *, allow_ref: bool = False
):
    """Reject constraints that cannot be represented by separate parameters."""
    supported = {
        "type",
        "properties",
        "required",
        "title",
        "description",
        "$comment",
    }
    if allow_ref:
        supported.add("$ref")
    unsupported = schema.keys() - supported
    if "type" in schema and schema["type"] != "object":
        unsupported.add("type")
    if unsupported:
        raise ValueError(
            f"Cannot expand parameter model constraints: {', '.join(sorted(unsupported))}."
        )
    constraints = schema.get("properties", {})
    extra_required = schema.get("required", [])
    unknown = (constraints.keys() | set(extra_required)) - properties.keys()
    if unknown:
        raise ValueError(
            "Cannot expand parameter model constraints for undeclared fields: "
            f"{', '.join(sorted(unknown))}."
        )


def _parameter_model(schema: dict, components: dict[str, dict]) -> dict:
    """Resolve a local model reference and preserve representable siblings."""
    ref = schema.get("$ref", "")
    prefix = "#/components/schemas/"
    if not ref.startswith(prefix):
        return schema
    model = components.get(ref.removeprefix(prefix), {})
    if model.get("type") != "object" or "properties" not in model:
        return schema

    _check_parameter_constraints(schema, model["properties"], allow_ref=True)

    properties = model["properties"].copy()
    for name, constraint in schema.get("properties", {}).items():
        properties[name] = _constrain_parameter_schema(properties[name], constraint)
    return {
        **model,
        "properties": properties,
        "required": list(
            dict.fromkeys([*model.get("required", []), *schema.get("required", [])])
        ),
    }


def _schema_for_type(
    type_: Any,
    components: dict[str, dict],
    schema_hook: Optional[Callable[[type], dict[str, Any]]],
) -> dict:
    schemas, definitions = msgspec.json.schema_components(
        (type_,),
        schema_hook=schema_hook,
        ref_template="#/components/schemas/{name}",
    )
    for name, definition in definitions.items():
        if name in components and components[name] != definition:
            raise ValueError(
                f"Conflicting schema name {name!r}; use distinct model names."
            )
        components[name] = definition
    return schemas[0]


def _parameters(
    type_: Any,
    location: ParameterLocation,
    components: dict[str, dict],
    schema_hook: Optional[Callable[[type], dict[str, Any]]],
) -> list[OpenAPIParam]:
    schema = _schema_for_type(type_, components, schema_hook)
    model = _parameter_model(schema, components)
    if model.get("type") == "object" and "properties" in model:
        _check_parameter_constraints(model, model["properties"])
        required = model.get("required", [])
        # Copy fields separately: hooks may reuse a schema dictionary.
        parameters = [
            OpenAPIParam(
                name=name,
                located_in=location,
                required=location == "path" or name in required,
                schema=deepcopy(field),
                description=field.get("description", "")
                if isinstance(field, dict)
                else "",
            )
            for name, field in model["properties"].items()
        ]
    elif location == "path":
        raise ValueError("path_type must be an object model with named fields.")
    else:
        parameters = [
            OpenAPIParam(
                name=type_.__name__,
                located_in=location,
                schema=deepcopy(model),
                description=get_def_doc(type_),
            )
        ]
    if location == "header":
        reserved = [
            param.name
            for param in parameters
            if param.name.lower() in ("accept", "content-type", "authorization")
        ]
        if reserved:
            raise ValueError(
                f"Cannot define reserved header parameters: {', '.join(sorted(reserved))}. "
                "Use security schemes for Authorization and media types for "
                "Accept and Content-Type."
            )
    return parameters


class OpenAPI(msgspec.Struct, kw_only=True):
    """OpenAPI specification.

    Usage:
        >>> openapi = OpenAPI()
        >>> # init with customized info
        >>> openapi = OpenAPI(
        >>>     info=OpenAPIInfo(title="My API", version="1.2.3"),
        >>>     components=OpenAPIComponent(
        >>>         security_schemes={
        >>>             "APIKey": SecuritySchemeAPIKey(name="X-Auth-Token")
        >>>         }
        >>>     ),
        >>> )
    """

    openapi: str = "3.1.0"
    info: OpenAPIInfo = msgspec.field(default_factory=OpenAPIInfo)
    paths: dict[str, dict[str, OpenAPIRoute]] = msgspec.field(
        default_factory=lambda: defaultdict(dict)
    )
    components: OpenAPIComponent = msgspec.field(default_factory=OpenAPIComponent)
    security: list[dict[str, list[str]]] = msgspec.field(default_factory=list)

    def __post_init__(self):
        if not re.fullmatch(r"3\.1\.\d+", self.openapi):
            raise ValueError("Only OpenAPI 3.1.x is supported.")

    @property
    def defs(self) -> dict[str, dict]:
        """Compatibility alias for components.schemas; never serialized as $defs."""
        return self.components.schemas

    def _check_route(self, path: str, method: str, operation_id: str) -> frozenset[str]:
        if method not in get_args(HTTP_METHODS):
            raise ValueError(f"Unsupported OpenAPI 3.1 method: {method!r}")
        if not path.startswith("/") or "?" in path or "#" in path:
            raise ValueError(
                "Paths must start with '/' and omit queries and fragments."
            )
        normalized, placeholders = _parse_path(path)
        for existing_path, routes in self.paths.items():
            if (
                placeholders
                and existing_path != path
                and "{" in existing_path
                and _normalized_path(existing_path) == normalized
            ):
                raise ValueError(
                    f"Equivalent path template already exists: {existing_path!r}"
                )
            for existing_method, route in routes.items():
                if route.operation_id == operation_id and (
                    existing_path != path or existing_method != method
                ):
                    raise ValueError(
                        f"Duplicate operationId {operation_id!r}; provide a unique operation_id."
                    )
        return placeholders

    def register_route(  # noqa: PLR0913
        self,
        path: str,
        method: str,
        summary: Optional[str] = None,
        request_type: Any = None,
        request_content_type: Optional[str] = None,
        response_type: Any = None,
        response_content_type: Optional[str] = None,
        query_type: Any = None,
        header_type: Any = None,
        cookie_type: Any = None,
        deprecated: bool = False,
        schema_hook: Optional[Callable[[type], dict[str, Any]]] = None,
        *,
        path_type: Any = None,
        operation_id: Optional[str] = None,
        security: Optional[list[dict[str, list[str]]]] = None,
    ):
        """Add or replace an endpoint in the OpenAPI document, with a 200 response.

        Each field in a query, header, cookie, or path model becomes a named parameter.
        Fields with defaults are optional unless the schema requires them. Path fields
        must match the URL placeholders and are always required. Parameter schemas are
        copied so editing a parameter does not change a shared body schema.

        Pass type(None) to describe a JSON null body. Passing None means no body.
        Invalid routes, conflicting names, and unsupported parameter constraints
        raise ValueError. Failed registration leaves the document unchanged.

        Args:
            path: Endpoint URL, such as /users/{id}.
            method: HTTP method in any letter case. CONNECT is unsupported.
            summary: Short description shown in the API documentation.
            request_type: Type of the request body, or None to omit it.
            request_content_type: Request media type; defaults to application/json.
            response_type: Type of the response body, or None for no response content.
            response_content_type: Response media type; defaults to application/json.
            query_type: Model with query fields, or a named scalar type.
            header_type: Model with header fields, or a named scalar type.
            cookie_type: Model with cookie fields, or a named scalar type.
            deprecated: Mark this endpoint as deprecated.
            schema_hook: Function that describes types msgspec does not recognize.
            path_type: Model with one field for each URL placeholder.
            operation_id: Unique name used by API clients. Defaults to the path with
                slashes replaced by underscores, then the method, such as _users_get.
            security: None uses global security; [] makes this endpoint public.
        """
        method = method.lower()
        operation_id = (
            operation_id
            if operation_id is not None
            else f"{path.replace('/', '_')}_{method}"
        )
        placeholders = self._check_route(path, method, operation_id)
        # Stage all changes so a failure cannot overwrite an existing operation
        # or leave unused schema definitions behind.
        components = self.components.schemas.copy()
        request_body = (
            OpenAPIRequestBody.with_schema_content_type(
                _schema_for_type(request_type, components, schema_hook),
                request_content_type,
            )
            if request_type is not None
            else msgspec.UNSET
        )
        response = (
            OpenAPIResponse.with_schema_content_type(
                _schema_for_type(response_type, components, schema_hook),
                response_content_type,
            )
            if response_type is not None
            else OpenAPIResponse()
        )
        parameters: list[OpenAPIParam] = []
        location: ParameterLocation
        for location, type_ in (
            ("query", query_type),
            ("header", header_type),
            ("cookie", cookie_type),
            ("path", path_type),
        ):
            if type_ is not None:
                parameters.extend(_parameters(type_, location, components, schema_hook))
        path_parameters = {
            param.name for param in parameters if param.located_in == "path"
        }
        if placeholders != path_parameters:
            raise ValueError(
                "path_type fields must exactly match the path placeholders."
            )
        route = OpenAPIRoute(
            summary=summary or f"{method} from {path.replace('/', ' ')}",
            operation_id=operation_id,
            request_body=request_body,
            responses={"200": response},
            parameters=parameters,
            deprecated=deprecated,
            security=msgspec.UNSET if security is None else security,
        )
        self.components.schemas.update(components)
        self.paths.setdefault(path, {})[method] = route

    def to_json(self) -> bytes:
        """Convert to a JSON bytes that is commonly used in HTTP endpoint."""
        return msgspec.json.encode(self)

    def to_dict(self) -> dict:
        """Convert to a dict."""
        return msgspec.to_builtins(self)

    def serve_as_http_daemon(
        self, host: str = "127.0.0.1", port: int = 8080, run_in_background: bool = False
    ):
        """Serve the OpenAPI specification and UI as a HTTP server.

        - `/openapi/spec.json`: the OpenAPI specification
        - `/openapi/swagger`: the Swagger UI
        - `/openapi/redoc`: the ReDoc UI
        - `/openapi/scalar`: the Scalar UI

        Args:
            host: host to serve
            port: port to serve
            run_in_background: whether to run in a daemon thread
        """
        serve_openapi_http_daemon(host, port, run_in_background, self.to_json())
